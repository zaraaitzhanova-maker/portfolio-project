"""## Step 3. Backtest engine
Each day: strategy → weights → 0.1% commission on turnover → daily return → log.

If a strategy returns `None` on a given day (e.g. Method 1 only re-optimizes every 5 days), we **hold the previous weights** rather than skipping the day.

Metrics: **Sharpe** (>1 ok, >2 great), **Sortino** (only penalizes losses), **Drawdown** (worst peak-to-trough loss).
"""

def run_backtest(weights_func, name, start_idx=60):
    portfolio_value = STARTING_CAPITAL
    prev_weights = None
    log = []
    for i in range(start_idx, len(returns)):
        new_weights = weights_func(i)
        if new_weights is None:
            if prev_weights is None: continue
            weights = prev_weights
            turnover = 0.0
        else:
            weights = new_weights
            if prev_weights is not None:
                turnover = sum(abs(weights.get(t, 0) - prev_weights.get(t, 0)) for t in TICKERS)
            else:
                turnover = sum(weights.get(t, 0) for t in TICKERS)
        portfolio_value -= portfolio_value * turnover * TRANSACTION_COST
        today = returns[TICKERS].iloc[i]
        port_ret = sum(weights.get(t, 0) * today[t] for t in TICKERS)
        portfolio_value *= (1 + port_ret)
        log.append({'date': returns.index[i], 'value': portfolio_value, 'daily_return': port_ret})
        prev_weights = weights
    return pd.DataFrame(log).set_index('date')

def metrics(df, name):
    r = df['daily_return']
    final = df['value'].iloc[-1]
    sharpe = (r.mean() / r.std()) * np.sqrt(252) if r.std() > 0 else 0
    downside = r[r < 0]
    sortino = (r.mean() / downside.std()) * np.sqrt(252) if len(downside) and downside.std() > 0 else 0
    dd = ((df['value'] - df['value'].cummax()) / df['value'].cummax()).min() * 100
    return {'Method': name, 'Final ($)': round(final, 2),
            'Return (%)': round((final/STARTING_CAPITAL - 1)*100, 1),
            'Sharpe': round(sharpe, 2), 'Sortino': round(sortino, 2),
            'Drawdown (%)': round(dd, 1)}

def select_10(mu, cov_mat):
    """Helper for Methods 2, 4, 5: pick top in each sector + top-5 by Sharpe."""
    sharpe = mu / np.sqrt(np.diag(cov_mat))
    selected = set()
    for sector_tix in STOCK_POOL.values():
        idx = [TICKERS.index(t) for t in sector_tix]
        selected.add(idx[np.argmax(sharpe[idx])])
    rem = sorted([k for k in range(len(TICKERS)) if k not in selected], key=lambda k: -sharpe[k])
    while len(selected) < 10 and rem: selected.add(rem.pop(0))
    return sorted(selected)

