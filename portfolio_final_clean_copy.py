"""## Method 1 — MINLP with Pyomo + Bonmin (Prof. Wanik / Womack approach)

**This is the original formulation from the lecture notebook.** Mixed-Integer Nonlinear Program (MINLP).

"""

def solve_minlp(mu, cov, n_select=10, w_min=0.05, w_max=0.30):
    """Womack-style MINLP via Pyomo + Bonmin. Falls back to scipy + greedy selection if Bonmin unavailable."""
    n = len(mu)
    if BONMIN_PATH is None:
        # Scipy fallback: continuous QP, then greedy round to 10 with linking constraints
        return _scipy_minlp_fallback(mu, cov, n_select, w_min, w_max)
    m = ConcreteModel()
    m.I = range(n)
    m.y = Var(m.I, domain=Binary)
    m.x = Var(m.I, domain=NonNegativeReals, bounds=(0, w_max))
    m.sum_x = Constraint(expr=sum(m.x[i] for i in m.I) == 1)
    m.sum_y = Constraint(expr=sum(m.y[i] for i in m.I) == n_select)
    m.link_lo = Constraint(m.I, rule=lambda m, i: m.x[i] >= w_min * m.y[i])
    m.link_hi = Constraint(m.I, rule=lambda m, i: m.x[i] <= w_max * m.y[i])
    sector_constraints = []
    for sector, tix in STOCK_POOL.items():
        idx = [TICKERS.index(t) for t in tix]
        sector_constraints.append(sum(m.y[i] for i in idx) >= 1)
    m.sector_min = Constraint(range(len(sector_constraints)),
                              rule=lambda m, k: sector_constraints[k])
    def sharpe_obj(m):
        ret = sum(mu[i] * m.x[i] for i in m.I)
        var = sum(cov[i, j] * m.x[i] * m.x[j] for i in m.I for j in m.I)
        return ret / pyo_sqrt(var + 1e-10)
    m.obj = Objective(rule=sharpe_obj, sense=maximize)
    solver = SolverFactory('bonmin', executable=BONMIN_PATH)
    try:
        solver.solve(m, tee=False)
        return np.array([value(m.x[i]) for i in m.I])
    except Exception:
        return _scipy_minlp_fallback(mu, cov, n_select, w_min, w_max)

def _scipy_minlp_fallback(mu, cov, n_select=10, w_min=0.05, w_max=0.30):
    """Approximate MINLP: pick top stocks by Sharpe (1 per sector + top by Sharpe), then continuous QP."""
    selected = select_10(mu, cov)
    sub_mu = mu[selected]; sub_cov = cov[np.ix_(selected, selected)]
    res = minimize(lambda w: -((w@sub_mu) / np.sqrt(w@sub_cov@w + 1e-10)),
                   np.ones(n_select)/n_select, method='SLSQP',
                   bounds=[(w_min, w_max)]*n_select,
                   constraints=[{'type':'eq','fun':lambda w: w.sum()-1}])
    if not res.success: return None
    x = np.zeros(len(mu))
    for idx, val in zip(selected, res.x): x[idx] = val
    return x

