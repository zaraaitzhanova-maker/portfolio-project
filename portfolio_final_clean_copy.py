"""## Method 3 — Hierarchical Risk Parity (HRP)

**Why HRP:** classical optimizers invert the covariance matrix — unstable on small samples. HRP avoids inversion entirely:
1. Compute correlations → distances
2. Build cluster tree (single-linkage)
3. Allocate risk by recursive bisection

Source: López de Prado, *JoPM 2016*. Used at JPMorgan, AQR, Two Sigma.
"""

def hrp_weights_from_cov(cov):
    std = np.sqrt(np.diag(cov))
    corr = np.clip(cov / np.outer(std, std), -1, 1)
    np.fill_diagonal(corr, 1.0)
    dist = np.sqrt(0.5 * (1 - corr))
    link = linkage(squareform(dist, checks=False), method='single')
    def get_quasi_diag(link):
        link = link.astype(int)
        sort_ix = pd.Series([link[-1, 0], link[-1, 1]])
        n_items = link[-1, 3]
        while sort_ix.max() >= n_items:
            sort_ix.index = range(0, sort_ix.shape[0]*2, 2)
            df0 = sort_ix[sort_ix >= n_items]
            i = df0.index; j = df0.values - n_items
            sort_ix[i] = link[j, 0]
            df0 = pd.Series(link[j, 1], index=i+1)
            sort_ix = pd.concat([sort_ix, df0]).sort_index()
        return sort_ix.tolist()
    sort_ix = get_quasi_diag(link)
    w = pd.Series(1.0, index=sort_ix)
    clusters = [sort_ix]
    while len(clusters) > 0:
        clusters = [c[s:e] for c in clusters
                    for s, e in ((0, len(c)//2), (len(c)//2, len(c))) if len(c) > 1]
        for i in range(0, len(clusters), 2):
            c0, c1 = clusters[i], clusters[i+1]
            def cluster_var(c):
                sub = cov[np.ix_(c, c)]
                ivp = 1.0 / np.diag(sub); ivp /= ivp.sum()
                return ivp @ sub @ ivp
            v0, v1 = cluster_var(c0), cluster_var(c1)
            alpha = 1 - v0 / (v0 + v1)
            w[c0] *= alpha; w[c1] *= (1 - alpha)
    return w.sort_index()

def method3_weights(i):
    if i < 60: return None
    cov_history = returns[TICKERS].iloc[i-60:i]
    lw = LedoitWolf(); lw.fit(cov_history.values); cov_mat = lw.covariance_
    try:
        w_arr = hrp_weights_from_cov(cov_mat).values
    except Exception:
        return None
    w_arr = np.clip(w_arr, 0.02, 0.30); w_arr /= w_arr.sum()
    return dict(zip(TICKERS, w_arr))
print('Method 3 (HRP) ✅')

"""## Method 4 — Black-Litterman (Goldman Sachs, 1990)

Start from market equilibrium (what prices imply), overlay views with proper uncertainty weighting.
Result: Method 2-style weights but **much more stable**.
"""

def method4_weights(i):
    if i < 273: return None
    history = returns[TICKERS].iloc[max(0, i-252):i]
    cov_history = returns[TICKERS].iloc[i-60:i]
    lw = LedoitWolf(); lw.fit(cov_history.values); Sigma = lw.covariance_
    n = len(TICKERS)
    w_market = np.ones(n) / n
    delta = 2.5
    pi = delta * Sigma @ w_market
    momentum = (history.iloc[-252:-21].sum() / 252).values
    ewma = history.ewm(halflife=20).mean().iloc[-1].values
    Q = 0.5 * momentum + 0.5 * ewma
    P = np.eye(n)
    tau = 0.05
    Omega = np.diag(np.diag(P @ (tau * Sigma) @ P.T))
    inv_tau_sigma = np.linalg.inv(tau * Sigma)
    inv_omega = np.linalg.inv(Omega + 1e-8 * np.eye(n))
    A = inv_tau_sigma + P.T @ inv_omega @ P
    b = inv_tau_sigma @ pi + P.T @ inv_omega @ Q
    mu_bl = np.linalg.solve(A, b)
    selected = select_10(mu_bl, Sigma)
    sub_mu = mu_bl[selected]; sub_cov = Sigma[np.ix_(selected, selected)]
    res = minimize(lambda w: -(w@sub_mu - delta*0.5*w@sub_cov@w), np.ones(10)/10,
                   method='SLSQP', bounds=[(0.05, 0.30)]*10,
                   constraints=[{'type':'eq','fun':lambda w: w.sum()-1}])
    if not res.success: return None
    w = pd.Series(0.0, index=TICKERS)
    for idx, val in zip(selected, res.x): w[TICKERS[idx]] = val
    return w.to_dict()
print('Method 4 (Black-Litterman) ✅')

"""## Method 5 — Fama-French 5-factor model

Eugene Fama's Nobel-Prize work (2013).
"""

def method5_weights(i):
    if ff5 is None: return None
    if i < 273: return None
    history = returns[TICKERS].iloc[max(0, i-252):i]
    factors = ff5.iloc[max(0, i-252):i]
    if len(factors) < 200: return None
    cov_history = returns[TICKERS].iloc[i-60:i]
    lw = LedoitWolf(); lw.fit(cov_history.values); cov_mat = lw.covariance_
    F = factors[['Mkt-RF', 'SMB', 'HML', 'RMW', 'CMA']].values
    F_mean = F.mean(axis=0)
    F_design = np.column_stack([np.ones(len(F)), F])
    mu = np.zeros(len(TICKERS))
    for k, t in enumerate(TICKERS):
        y = history[t].values - factors['RF'].values
        beta, _, _, _ = np.linalg.lstsq(F_design, y, rcond=None)
        mu[k] = beta[0] + beta[1:] @ F_mean + factors['RF'].mean()
    selected = select_10(mu, cov_mat)
    sub_mu = mu[selected]; sub_cov = cov_mat[np.ix_(selected, selected)]
    res = minimize(lambda w: -(w@sub_mu - 2.5*0.5*w@sub_cov@w), np.ones(10)/10,
                   method='SLSQP', bounds=[(0.05, 0.30)]*10,
                   constraints=[{'type':'eq','fun':lambda w: w.sum()-1}])
    if not res.success: return None
    w = pd.Series(0.0, index=TICKERS)
    for idx, val in zip(selected, res.x): w[TICKERS[idx]] = val
    return w.to_dict()
print('Method 5 (Fama-French) ✅')

